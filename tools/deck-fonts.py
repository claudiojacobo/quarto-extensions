#!/usr/bin/env python3
"""Write cjgg's _fonts.scss: the slides' fonts (cjgg-revealjs), inside the
stylesheet, so a deck needs no network for them (Google Fonts did).

    python3 tools/deck-fonts.py <@fontsource/montserrat folder> <@fontsource/playfair-display folder>

Each folder is an unpacked Fontsource package (npm pack @fontsource/montserrat,
then tar xzf; the files are in package/). The faces the look uses, latin
subset, are embedded as woff2 data with the unicode-range of Fontsource's own
CSS, and the two licenses are written beside the stylesheet as fonts-OFL.txt:
both fonts are under the SIL Open Font License 1.1, which asks that the
license travel with the fonts. Run it again only to change fonts or versions;
_fonts.scss's header says which files, versions and sums it holds.
"""
import base64
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "cjgg/_extensions/cjgg/_fonts.scss"
LICENSE_OUT = ROOT / "cjgg/_extensions/cjgg/fonts-OFL.txt"

# (family, Fontsource name, weight, style): what revealjs.scss uses
FACES = [
    ("Montserrat", "montserrat", 400, "normal"),
    ("Montserrat", "montserrat", 400, "italic"),
    ("Montserrat", "montserrat", 600, "normal"),
    ("Montserrat", "montserrat", 700, "normal"),
    ("Playfair Display", "playfair-display", 600, "normal"),
    ("Playfair Display", "playfair-display", 600, "italic"),
]


def package(folder: Path) -> Path:
    return folder / "package" if (folder / "package" / "package.json").exists() else folder


def main(folders):
    pkgs = {}
    for f in folders:
        p = package(Path(f))
        meta = json.loads((p / "package.json").read_text())
        pkgs[meta["name"].split("/")[-1]] = (p, meta)
    for need in {face[1] for face in FACES}:
        if need not in pkgs:
            sys.exit(f"missing the @fontsource/{need} package folder")

    listed, rules = [], []
    for family, name, weight, style in FACES:
        p, meta = pkgs[name]
        stem = f"{name}-latin-{weight}-{style}"
        woff2 = (p / "files" / f"{stem}.woff2").read_bytes()
        css = (p / f"{weight}{'-italic' if style == 'italic' else ''}.css").read_text()
        block = re.search(rf"/\* {stem} \*/\s*@font-face\s*{{(.*?)}}", css, re.S)
        uni = re.search(r"unicode-range:\s*([^;]+);", block.group(1)).group(1).strip() if block else None
        if not uni:
            sys.exit(f"no unicode-range for {stem} in Fontsource's CSS")
        listed.append(f"//   {stem}.woff2  {len(woff2)} bytes  sha256 {hashlib.sha256(woff2).hexdigest()}  (@fontsource/{name} {meta['version']})")
        rules.append(
            "@font-face {\n"
            f"  font-family: \"{family}\";\n"
            f"  font-style: {style};\n"
            f"  font-weight: {weight};\n"
            "  font-display: swap;\n"
            f"  src: url(\"data:font/woff2;base64,{base64.b64encode(woff2).decode('ascii')}\") format(\"woff2\");\n"
            f"  unicode-range: {uni};\n"
            "}\n")

    OUT.write_text(
        "/* _fonts.scss — GENERATED by tools/deck-fonts.py; do not edit.\n"
        "   The slides' fonts (cjgg-revealjs), inside the stylesheet so a deck needs\n"
        "   no network: Montserrat (Copyright 2011 The Montserrat Project Authors) and\n"
        "   Playfair Display (Copyright 2017 The Playfair Display Project Authors,\n"
        "   Reserved Font Name \"Playfair Display\"), both under the SIL Open Font\n"
        "   License 1.1 (fonts-OFL.txt, beside this file); the files unchanged from\n"
        "   Fontsource's packages, latin subset. */\n"
        "// Faces:\n" + "\n".join(listed) + "\n"
        "/*-- scss:rules --*/\n" + "\n".join(rules))
    LICENSE_OUT.write_text(
        "The fonts in _fonts.scss (the slides' fonts, cjgg-revealjs) and their licenses,\n"
        "as Fontsource's packages give them.\n\n"
        + "\n\n".join(f"===== {pkgs[n][1]['name']} {pkgs[n][1]['version']} =====\n\n{(pkgs[n][0] / 'LICENSE').read_text().strip()}"
                      for n in ("montserrat", "playfair-display")) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB, {len(FACES)} faces) and {LICENSE_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1:])
