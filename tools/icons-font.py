#!/usr/bin/env python3
"""Write mathkit's _icons.scss: the Bootstrap Icons the stylesheets use, as a
font inside the stylesheet, for slides.

Web pages get Bootstrap Icons from Bootstrap; a reveal.js deck has no
Bootstrap, so the block headers' icons, the proofs' tombstones and the rest
need the font brought along. Only the icons the extensions' stylesheets name
("\\F46B" and so on) are kept, so the font is a few kilobytes, and it is
inside the stylesheet, so a deck needs no file of its own and works offline.

    python3 tools/icons-font.py path/to/bootstrap-icons.woff   # write it
    python3 tools/icons-font.py --check                         # tools/check-generated.sh

The .woff is Quarto's own copy (site_libs/bootstrap/bootstrap-icons.woff in
any rendered site). Writing needs fontTools (pip install fonttools);
--check needs nothing: it fails if a stylesheet names an icon the font
lacks, so run the first form after adding an icon to a stylesheet.
Bootstrap Icons: MIT License, https://github.com/twbs/icons.
"""
import base64
import io
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "mathkit/_extensions/mathkit/_icons.scss"
CODE = re.compile(r'"\\(F[0-9A-Fa-f]{3})"')
LISTED = re.compile(r"^// Icons: (.*)$", re.M)


def used():
    found = set()
    for ext in ("mathkit", "cjgg"):
        for f in sorted((ROOT / ext / "_extensions" / ext).glob("*.scss")):
            if f.name == "_icons.scss":
                continue
            found |= {c.upper() for c in CODE.findall(f.read_text())}
    return sorted(found)


def check():
    if not OUT.exists():
        sys.exit(f"{OUT} is missing: run tools/icons-font.py with Bootstrap Icons' .woff")
    m = LISTED.search(OUT.read_text())
    have = set(m.group(1).split()) if m else set()
    missing = [c for c in used() if c not in have]
    if missing:
        sys.exit("The slides' icon font lacks " + " ".join(missing)
                 + ": run tools/icons-font.py with Bootstrap Icons' .woff")


def write(woff):
    from fontTools import subset
    from fontTools.ttLib import TTFont
    codes = used()
    font = TTFont(woff)
    cmap = font.getBestCmap()
    absent = [c for c in codes if int(c, 16) not in cmap]
    if absent:
        sys.exit("Not in this Bootstrap Icons font: " + " ".join(absent))
    opts = subset.Options()
    opts.flavor = "woff"
    opts.layout_features = []
    opts.name_IDs = [0, 1, 2, 5]   # copyright, family, style, version
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=[int(c, 16) for c in codes])
    sub.subset(font)
    buf = io.BytesIO()
    font.flavor = "woff"
    font.save(buf)
    data = base64.b64encode(buf.getvalue()).decode("ascii")
    OUT.write_text(
        "/* _icons.scss — GENERATED by tools/icons-font.py; do not edit.\n"
        "   The Bootstrap Icons the stylesheets use, as a font inside the stylesheet,\n"
        "   for slides (web pages have Bootstrap's own). From Quarto's copy of\n"
        "   Bootstrap Icons (MIT License, https://github.com/twbs/icons). */\n"
        "// Icons: " + " ".join(codes) + "\n"
        "/*-- scss:rules --*/\n"
        "@font-face {\n"
        "  font-family: \"bootstrap-icons\";\n"
        "  font-display: block;\n"
        "  src: url(\"data:font/woff;base64," + data + "\") format(\"woff\");\n"
        "}\n")
    print(f"{OUT.relative_to(ROOT)}: {len(codes)} icons, {len(buf.getvalue())} bytes of font")


if __name__ == "__main__":
    if sys.argv[1:] == ["--check"]:
        check()
    elif len(sys.argv) == 2:
        write(sys.argv[1])
    else:
        sys.exit(__doc__)
